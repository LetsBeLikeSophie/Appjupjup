export const dicts = { ko, en };
export type Locale = keyof typeof dicts;

export function pickLocale(pref?: string | null): Locale {
  const l = (pref || (typeof navigator !== 'undefined' ? navigator.language : 'ko')).slice(0, 2);
  return l === 'ko' ? 'ko' : 'en';
}

export function guessCountry(): string {
  if (typeof navigator === 'undefined') return 'KR';
  const m = navigator.language.match(/-([A-Z]{2})$/i);
  return m ? m[1].toUpperCase() : navigator.language.startsWith('ko') ? 'KR' : 'US';
}
